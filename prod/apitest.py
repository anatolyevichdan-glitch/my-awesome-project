import skia, numpy as np
a = np.zeros((1920, 1080, 4), np.uint8)
s = skia.Surface(a); c = s.getCanvas()
c.clear(skia.ColorBLACK)
p = skia.Paint(AntiAlias=True, Shader=skia.GradientShader.MakeLinear([(0, 0), (0, 100)], [skia.ColorRED, skia.ColorBLUE]))
c.drawRect(skia.Rect(0, 0, 100, 100), p)
p2 = skia.Paint(AntiAlias=True, Color=skia.ColorWHITE, MaskFilter=skia.MaskFilter.MakeBlur(skia.kNormal_BlurStyle, 10))
c.drawCircle(300, 300, 50, p2)
c.saveLayer(); c.drawCircle(500, 500, 50, skia.Paint(Color=skia.ColorGREEN))
c.drawPaint(skia.Paint(Color=skia.ColorSetARGB(128, 255, 0, 0), BlendMode=skia.BlendMode.kSrcATop)); c.restore()
tf = skia.Typeface.MakeFromFile('fonts/Montserrat-ExtraBold.ttf'); print(tf)
f = skia.Font(tf, 60); c.drawString("Привет", 100, 800, f, skia.Paint(Color=skia.ColorWHITE)); print(f.measureText("Привет"))
img = skia.Image.fromarray(np.random.randint(0, 255, (64, 64, 4), np.uint8)); print(img)
sh = img.makeShader(skia.TileMode.kRepeat, skia.TileMode.kRepeat)
c.drawRect(skia.Rect(0, 1000, 300, 1300), skia.Paint(Shader=sh))
print(a[50, 50], a[300, 300], a[500, 500], a[1100, 100])
